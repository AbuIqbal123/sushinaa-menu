import { test, expect } from '@playwright/test';
import { admin } from './admin';

test.use({ viewport: { width:390, height:844 } });
for(const lang of ['en','ar']) test(`mandatory branded car picker completes checkout and reaches CMS (${lang})`,async({page,browser,baseURL},info)=>{
  await page.context().addCookies([{name:'sushina-lang',value:lang,url:baseURL!}]);
  await page.goto('/down-town');
  await page.locator('#dish-sushinaa-burger .slide-hit').click();
  await page.locator('.detail-add').click(); await page.locator('.ticket-close').click();
  await page.locator('.sticky-cta').click();
  await page.getByRole('button',{name:lang === 'ar' ? 'اطلب للاستلام' : 'Order for pickup'}).click();
  await page.locator('#collection-name').fill('Preview guest');
  await page.locator('#collection-phone').fill('55551234');
  await page.locator('#collection-plate').fill('123456');
  await page.locator('.checkout-step-action button').click();
  await expect(page.locator('#hint-brand')).toBeVisible();
  await expect(page.locator('#collection-brand')).toBeFocused();
  await expect(page.locator('#collection-name')).toBeVisible();
  // Server validation is mandatory too; the UI cannot be bypassed.
  const customer={name:'Preview guest',phone:'55551234',plate:'Q123456'};
  const payload={branchId:'down-town',paymentMethod:'mock',customer,lines:[{dishId:'sushinaa-burger',selection:{},quantity:1,note:'',expectedUnitMinor:5300}]};
  for(const candidate of [customer,{...customer,brand:'invented-brand'}]) {
    const r=await page.request.post('/api/orders',{headers:{Origin:baseURL!,'Idempotency-Key':crypto.randomUUID()},data:{...payload,customer:candidate}});
    expect(r.status()).toBe(400);expect(await r.json()).toEqual({code:'INVALID'});
  }
  await page.locator('#collection-brand').press('ArrowDown');
  const dialog=page.getByRole('dialog'); await expect(dialog).toBeVisible();
  await expect(dialog).toHaveAttribute('dir',lang === 'ar' ? 'rtl' : 'ltr');
  await expect(dialog.locator('.car-brand-option')).toHaveCount(98);
  await expect(dialog.locator('[data-brand-id="audi"] .car-brand-logo > span')).toHaveCSS('background-image',/reference-1.jpg/);
  await expect(dialog).toHaveCSS('opacity','1');
  await page.screenshot({path:info.outputPath(`brand-picker-${lang}.png`)});
  const search=dialog.getByRole('searchbox');
  await search.fill('unknown-car'); await expect(dialog.locator('.car-brand-option')).toHaveCount(0);
  await expect(dialog.getByRole('status')).toBeVisible();
  await search.fill(lang==='ar' ? 'تويوتا' : 'TOYOTA');
  await expect(dialog.locator('.car-brand-option')).toHaveCount(1);
  await dialog.locator('[data-brand-id="toyota"]').click();
  await expect(dialog).toHaveCount(0);
  await expect(page.locator('#collection-brand')).toContainText(lang==='ar' ? 'تويوتا' : 'Toyota');
  await expect(page.locator('#hint-brand')).toHaveCount(0);
  await page.locator('#collection-brand').click();
  await page.getByRole('dialog').getByRole('searchbox').fill('Toyota');
  await expect(page.locator('[data-brand-id="toyota"]')).toHaveAttribute('aria-pressed','true');
  await page.getByRole('dialog').getByRole('searchbox').press('Enter');
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.locator('#collection-brand')).toBeFocused();
  await page.locator('.optional-vehicle summary').click();
  await page.locator('#collection-car').fill('Camry');
  await page.locator('.checkout-step-action button').click();
  await expect(page.locator('.review-details')).toContainText('Camry');
  await expect(page.locator('.review-details')).toContainText(lang==='ar' ? 'تويوتا' : 'Toyota');
  await page.locator('.checkout-step-action button').click();
  const paid=page.waitForResponse(r=>r.url().includes('/mock-pay') && r.request().method()==='POST');
  await page.locator('.sadad-pay').click();const id=(await(await paid).json()).id;
  await expect(page.locator('.order-vehicle')).toContainText('Camry');
  const staff=await browser.newContext({baseURL});
  expect((await staff.request.post('/api/admin/session',{headers:{Origin:baseURL!},data:admin})).status()).toBe(200);
  const details=await(await staff.request.get(`/api/admin/orders/${id}`)).json();
  expect(details.customer.brand).toBe('Toyota');expect(details.customer.car).toBe('Camry');
  expect((await(await staff.request.get(`/cms/orders/${id}/ticket`)).text())).toContain('Toyota');
  expect((await(await staff.request.get(`/cms/orders/${id}/receipt`)).text())).toContain('Toyota');
  const staffPage=await staff.newPage();await staffPage.goto('/admin');await staffPage.getByRole('button',{name:'Orders',exact:true}).click();
  await staffPage.locator(`[data-order-id="${id}"]`).click();await expect(staffPage.locator('.kitchen-facts')).toContainText('Toyota');
  await staff.close();
});
