export function findCarBrand(id: unknown) {
  return typeof id === 'string' ? CAR_BRANDS.find(brand => brand.id === id) : undefined;
}
export function carBrandName(id: unknown, lang: Lang = 'en') {
  const brand = findCarBrand(id);
  return brand ? (lang === 'ar' ? brand.ar : brand.name) : '';
}
const normalize = (s: string) => s.normalize('NFKC').toLowerCase().replace(/[أإآ]/g, 'ا').replace(/ى/g, 'ي').replace(/[\s._-]/g, '').replace(/[٠-٩]/g, n => String(n.charCodeAt(0) - 1632));
export function searchCarBrands(query: string) {
  const q = normalize(query.trim());
  return CAR_BRANDS.filter(brand => [brand.name, brand.ar, brand.id, ...(brand.id === 'avatr' ? ['Avatr'] : []), ...(brand.id === 'mercedes' ? ['Mercedes Benz'] : [])].some(name => normalize(name).includes(q)));
}
